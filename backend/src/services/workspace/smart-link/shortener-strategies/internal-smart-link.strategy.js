const BaseShortenerStrategy = require('./base-shortener.strategy');
const smartLinkRepository = require('../../../../repositories/workspace/smart-link.repository');
const prisma = require('../../../../config/prisma');
const appConfig = require('../../../../config/app.config');

class InternalSmartLinkStrategy extends BaseShortenerStrategy {
  async shorten(url, brandId) {
    if (!url || !brandId) return url;

    // Tìm SmartLink chính của Brand hoặc khởi tạo nếu chưa có
    let smartLink = await smartLinkRepository.findByBrandId(brandId);
    if (!smartLink) {
      const brand = await prisma.brand.findUnique({ where: { id: brandId } });
      const brandSlug = (brand?.name || 'brand').toLowerCase().replace(/[^a-z0-9]/g, '-') + '-' + Date.now().toString(36);
      
      smartLink = await smartLinkRepository.create({
        brandId,
        slug: brandSlug,
        pageTitle: brand?.name || 'SmartLink',
        backgroundType: 'PRESET',
        backgroundValue: 'gradient-blue',
        buttonStyle: 'rounded',
        isPublished: true
      });
    }

    const baseUrl = appConfig.backendBaseUrl;

    // Kiểm tra xem URL này đã được rút gọn chưa trong link items của SmartLink
    const existingItem = (smartLink.links || []).find(l => l.url === url);
    if (existingItem) {
      return `${baseUrl}/api/smart-links/r/${existingItem.id}`;
    }

    // Tạo LinkItem mới cho đường dẫn (đánh dấu isAutoGenerated: true để không hiện lên Bio Page /smartlinks)
    const nextPosition = (smartLink.links || []).length;
    const newItem = await prisma.linkItem.create({
      data: {
        smartLinkId: smartLink.id,
        title: url.replace(/^https?:\/\//i, '').substring(0, 30),
        url: url,
        position: nextPosition,
        isActive: true,
        isAutoGenerated: true
      }
    });

    return `${baseUrl}/api/smart-links/r/${newItem.id}`;
  }
}

module.exports = new InternalSmartLinkStrategy();
