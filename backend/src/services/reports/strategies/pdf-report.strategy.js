const path = require('path');
const PDFDocument = require('pdfkit');
const ReportGeneratorStrategy = require('./report-generator.strategy');

const FONT_PATH = path.join(__dirname, '../../../assets/fonts/NotoSans-Variable.ttf');

class PdfReportStrategy extends ReportGeneratorStrategy {
  async generate(title, brand, data, options = {}) {
    const brandName = brand?.name || 'PubliCast Brand';
    const logoText = options.isWhiteLabel ? `White-label (Logo: ${options.brandLogoUrl || 'Default'})` : 'Powered by PubliCast';
    const colorHex = options.brandColorHex || '#3B82F6';

    const doc = new PDFDocument({ margin: 50 });
    doc.registerFont('NotoSans', FONT_PATH);
    doc.font('NotoSans');

    const chunks = [];
    const bufferPromise = new Promise((resolve, reject) => {
      doc.on('data', chunk => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);
    });

    const rule = () => {
      doc.moveDown(0.3);
      doc.text('------------------------------------------------------------');
      doc.moveDown(0.3);
    };

    doc.fontSize(14).text(`BRAND ANALYTICS REPORT: ${title.toUpperCase()}`);
    doc.moveDown(0.5);
    doc.fontSize(10);
    doc.text(`Brand: ${brandName}`);
    doc.text(`Created Date: ${new Date().toLocaleDateString('vi-VN')}`);
    doc.text(`Theme Color: ${colorHex}`);
    doc.text(`Branding: ${logoText}`);

    rule();
    doc.fontSize(12).text('1. GENERAL PERFORMANCE OVERVIEW');
    doc.fontSize(10).moveDown(0.3);
    doc.text(`Total Reach: ${data.overview?.reach?.toLocaleString() || 0}`);
    doc.text(`Total Impressions: ${data.overview?.impressions?.toLocaleString() || 0}`);
    doc.text(`Total Engagements: ${data.overview?.engagements?.toLocaleString() || 0}`);
    doc.text(`Engagement Rate (AVG): ${data.overview?.engagementRate?.toFixed(2) || '0.00'}%`);

    rule();
    doc.fontSize(12).text('2. CHANNEL DETAILED ANALYTICS');
    doc.fontSize(10).moveDown(0.3);
    if (data.channels && data.channels.length > 0) {
      data.channels.forEach(ch => {
        doc.moveDown(0.3);
        doc.text(`Platform: ${ch.platform} (${ch.displayName})`);
        doc.text(`- Followers: ${ch.followers?.toLocaleString() || 0}`);
        doc.text(`- Posts: ${ch.postsCount || 0}`);
        doc.text(`- Engagement Rate: ${ch.engagementRate?.toFixed(2) || '0.00'}%`);
      });
    } else {
      doc.text('No active channel data linked for this report period.');
    }

    rule();
    doc.fontSize(12).text('3. TOP VIRAL POSTS');
    doc.fontSize(10).moveDown(0.3);
    if (data.topPosts && data.topPosts.length > 0) {
      data.topPosts.forEach((post, idx) => {
        doc.moveDown(0.3);
        doc.text(`[#${idx + 1}] Platform: ${post.platform}`);
        doc.text(`- Title/Caption: ${post.title || post.caption || 'No Title'}`);
        doc.text(`- Likes: ${post.likes || 0} | Comments: ${post.comments || 0} | Shares: ${post.shares || 0}`);
        doc.text(`- Engagement Rate: ${post.engagementRate || '0.0'}%`);
      });
    } else {
      doc.text('No posts found in the analytics range.');
    }

    rule();
    doc.text('Generated by PubliCast - Automated Analytics Platform');

    doc.end();

    const buffer = await bufferPromise;

    return {
      buffer,
      contentType: 'application/pdf',
      extension: 'pdf'
    };
  }
}

module.exports = PdfReportStrategy;
