export function PlatformIcon({ platform, size = 18, variant = "color", className = "" }) {
  const normPlatform = Object.keys(OFFICIAL_LOGOS).find(
    (k) => k.toLowerCase() === platform?.toLowerCase()
  ) || "YouTube";

  // Sử dụng logo ảnh thật nếu là YouTube (vừa tải về)
  if (normPlatform === "YouTube" && variant === "color") {
    return (
      <img 
        src={youtubeImg} 
        alt="YouTube" 
        className={`shrink-0 object-contain ${className}`}
        style={{ width: size, height: size }}
      />
    );
  }

  const renderSvg = OFFICIAL_LOGOS[normPlatform];
  const bg = PLATFORM_COLORS[normPlatform] || "#888";

  // Dành cho flat (khi chỉ cần màu thương hiệu đơn sắc hoặc icon trần không nền)
  if (variant === "flat") {
    return (
      <div 
        className={`flex items-center justify-center shrink-0 ${className}`} 
        style={{ width: size, height: size, color: bg }}
      >
        {renderSvg(size, true)}
      </div>
    );
  }

  // Chế độ color: Hiển thị logo thương hiệu thật, sắc nét, có background/gradient chuẩn chỉnh
  return (
    <div
      className={`flex items-center justify-center shrink-0 ${className}`}
      style={{
        width: size,
        height: size,
        display: 'inline-flex'
      }}
    >
      {renderSvg(size, false)}
    </div>
  );
}
